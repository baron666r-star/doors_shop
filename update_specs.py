import json

# Характеристики для первой двери (id=1)
specs = {
    "Количество замков": "2",
    "Внешняя отделка": "букле антацит",
    "Внутренняя отделка": "панель mdf, объемный рисунок",
    "Дополнительные опции": "терморазрыв",
    "Наполнитель": "пенополистирол + базальтовая плита",
    "Основной замок": "сувальдный гардиан",
    "Дополнительный замок": "сувальдный гардиан",
    "Ночная задвижка": "есть",
    "Глазок": "нет"
}

# Читаем базу
with open('doors.json', 'r', encoding='utf-8') as f:
    doors = json.load(f)

# Добавляем характеристики первой двери
for door in doors:
    if door['id'] == 1:
        door['specs'] = specs
        break

# Сохраняем
with open('doors.json', 'w', encoding='utf-8') as f:
    json.dump(doors, f, ensure_ascii=False, indent=4)

print("Характеристики успешно добавлены в базу!")